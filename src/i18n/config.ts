export function useTranslations(lang: keyof typeof ui | undefined) {
  if (!lang) lang = defaultLocale
  return function t(key: keyof (typeof ui)[typeof defaultLocale]) {
    return ui[lang][key] || ui[defaultLocale][key]
  }
}
